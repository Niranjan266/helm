package com.niranjan.helm.core

/*
 * The Bluetooth HID descriptor Helm registers when the phone acts as a mouse + keyboard.
 * Three top-level collections, told apart by report id. Plain bytes, no Android types.
 */

object HidIds {
    const val MOUSE = 1
    const val KEYBOARD = 2
    const val CONSUMER = 3
}

object HidDescriptor {
    val bytes: ByteArray by lazy {
        val d = ArrayList<Int>()
        fun add(vararg v: Int) = v.forEach { d += it and 0xFF }

        // ---- Mouse (report id 1): 5 buttons, X/Y 16-bit relative, wheel, horizontal pan -----
        add(0x05, 0x01, 0x09, 0x02, 0xA1, 0x01) // Usage Page (Generic Desktop), Usage (Mouse), Collection (Application)
        add(0x85, HidIds.MOUSE) //   Report ID
        add(0x09, 0x01, 0xA1, 0x00) //   Usage (Pointer), Collection (Physical)
        add(0x05, 0x09, 0x19, 0x01, 0x29, 0x05) //     Usage Page (Buttons), Usage Min 1, Max 5
        add(0x15, 0x00, 0x25, 0x01, 0x95, 0x05, 0x75, 0x01, 0x81, 0x02) //     5 x 1 bit, Input (Data, Var, Abs)
        add(0x95, 0x01, 0x75, 0x03, 0x81, 0x03) //     3 bits padding
        add(0x05, 0x01, 0x09, 0x30, 0x09, 0x31) //     Usage Page (Generic Desktop), Usage X, Usage Y
        add(0x16, 0x01, 0x80, 0x26, 0xFF, 0x7F) //     Logical Min -32767, Max 32767
        add(0x75, 0x10, 0x95, 0x02, 0x81, 0x06) //     2 x 16 bit, Input (Data, Var, Rel)
        add(0x09, 0x38, 0x15, 0x81, 0x25, 0x7F) //     Usage (Wheel), Logical Min -127, Max 127
        add(0x75, 0x08, 0x95, 0x01, 0x81, 0x06) //     1 x 8 bit, relative
        add(0x05, 0x0C, 0x0A, 0x38, 0x02) //     Usage Page (Consumer), Usage (AC Pan)
        add(0x95, 0x01, 0x75, 0x08, 0x81, 0x06) //     1 x 8 bit, relative
        add(0xC0, 0xC0) //   End Collection x2

        // ---- Keyboard (report id 2): 8 modifier bits, reserved byte, 6 key codes, 5 LEDs -----
        add(0x05, 0x01, 0x09, 0x06, 0xA1, 0x01)
        add(0x85, HidIds.KEYBOARD)
        add(0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7) //   Usage Page (Keyboard), Usage Min 0xE0, Max 0xE7
        add(0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02) //   8 x 1 bit modifiers
        add(0x95, 0x01, 0x75, 0x08, 0x81, 0x01) //   reserved byte (Constant)
        add(0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65) //   6 x 8 bit key codes, 0..101
        add(0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00)
        add(0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x95, 0x05, 0x75, 0x01, 0x91, 0x02) //   LEDs out (5 bits)
        add(0x95, 0x01, 0x75, 0x03, 0x91, 0x01) //   3 bits padding
        add(0xC0)

        // ---- Consumer control (report id 3): six 1-bit buttons ------------------------------
        add(0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01)
        add(0x85, HidIds.CONSUMER)
        add(0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x06)
        add(0x09, 0xCD, 0x09, 0xB5, 0x09, 0xB6, 0x09, 0xE9, 0x09, 0xEA, 0x09, 0xE2) // play/pause, next, prev, vol+, vol-, mute
        add(0x81, 0x02)
        add(0x95, 0x01, 0x75, 0x02, 0x81, 0x03) //   2 bits padding
        add(0xC0)

        ByteArray(d.size) { d[it].toByte() }
    }
}
